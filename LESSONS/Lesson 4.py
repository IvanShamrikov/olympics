# третьої секунди Козак Вус залишиться у координаті 0.
#
# У другому прикладі Козак Вус починає з координати 5.
# На початку першої секунди Козак Вус бачить число y1=2. Найближчими координатами до 5 кратними 2 є 4 та 6.
# Оскільки 4<6, то наприкінці першої секунди Козак Вус опиниться у координаті 4. На початку другої секунди Козак Вус
# бачить число y2=3. Найближчою координатою до 4 кратною 3 є 3. Тому наприкінці другої секунди Козак Вус залишиться у
# координаті 3.
# На початку третьої секунди Козак Вус бачить число y3=2. Найближчими координатами до 3 кратними 2 є 2 та 4.
# Оскільки 2<4, то наприкінці третьої секунди Козак Вус опиниться у координаті 2.
#
# У третьому прикладі Козак Вус починає з координати 10**4.
# На початку першої секунди Козак Вус бачить число y1=5001. Найближчою координатою до 10000 кратною 5001 є 10002.
# Тому наприкінці першої секунди Козак Вус опиниться у координаті 10002.
#
#
# Приклад 1
# Вхідні дані
# 3 2
# 2 4 1
# Вихідні дані
# 2 0 0
#
# Приклад 2
# Вхідні дані
# 3 5
# 2 3 2
# Вихідні дані
# 4 3 2
#
# Приклад 3
# Вхідні дані
# 1 10000
# 5001
# Вихідні дані
# 10002

n,x = map(int, input().split())
mas = list(map(int, input().split()))
result = []

for i in mas:
    left = (x // i) * i
    right = left + i

    dL = x - left
    dR = right - x

    if dL <= dR:
        x = left
    else:
        x = right
    result.append(str(x))

print(" ".join(result))


