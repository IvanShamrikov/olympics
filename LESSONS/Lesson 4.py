# Козак Вус і важлива знахідка
#
# Зовсім нещодавно мешканці Потоколяндії знайшли стародавню табличку розміром 2×2, в якій розташовано чотири
# числа A, B, C і D так:
# https://drive.google.com/file/d/1m29M2nlfc2l7HI2PMzu1-nZSkmumxY6l/view?usp=sharing
# Вони відразу зрозуміли, що це дуже важлива історична знахідка. Спершу вони віднесли її Козаку Вусу для того, щоб він
# визначив важливість цієї таблички. На думку Козака Вуса, важливість таблички дорівнює A⋅(B+C−D).
# На жаль, правильне положення таблички невідоме. Тому може статись таке, що однозначно визначити важливість таблички
# неможливо, оскільки це значення залежить від того, скільки разів її обернути.
# Припустимо, що один оберт — це оберт за годинниковою стрілкою на 90°.
# Наприклад, якщо A=41, B=99, C=100, D=13, то важливість рівна 41⋅(99+100−13)=7626. А якщо її один раз обернути,
# то 100⋅(41+13−99)=−4500.
# https://drive.google.com/file/d/1iLs-crOp86elXmNPxg4hlP9HZ6xzltCC/view?usp=sharing
# Козак Вус хоче з'ясувати, яку максимальну можливу важливість може мати ця знахідка. Але Вас він просить дізнатись, яку '
# мінімальну кількість обертів потрібно зробити для того, щоб важливість таблички була максимальною.Козак Вус хоче з')ясувати, яку максимальну можливу важливість може мати ця знахідка. Але Вас він просить дізнатись, яку мінімальну кількість обертів потрібно зробити для того, щоб важливість таблички була максимальною.
#
# Вхідні дані
# Перший рядок містить чотири цілих числа A, B, C i D (−10**8 ≤A,B,C,D≤10**8) — числа на табличці.
#
# Вихідні дані
# Виведіть мінімальну кількість обертів, які потрібно зробити Козаку Вусу, щоб важливість таблички була максимальною.
#
# Приклад 1
# Вхідні дані
# 5 3 4 6
# Вихідні дані
# 1
#
# Приклад 2
# Вхідні дані
# 2 9 -4 13
# Вихідні дані
# 3
#
# Приклад 3
# Вхідні дані
# 2 6 3 0
# Вихідні дані
# 0

n1,n2,n3,n4 = map(int, input().split())
variants = [[n1,n2,n3,n4],
            [n3,n1,n4,n2],
            [n4,n3,n2,n1],
            [n2,n4,n1,n3]]
mas = []
for var in variants:
    A = var[0]
    B = var[1]
    C = var[2]
    D = var[3]
    value = A*(B+C-D)
    mas.append( value )

max_value = max(mas)
print(mas.index(max_value))


