# Примітка для вчителя - якщо на прямій 4 точки, то до лічильника треба додати усі комбінації трійок з тих 4х точок.
# Тобто, для точок 1,2,3,4 такі комбінації будуть (1,2,3) (1,3,4) (2,3,4) (1,2,4)

#Це рішення рахує кількість прямих, а не комбінацій трійок. Для того, щоб порахувати комбінації трійок, треба  в
# останніх 2х циклах for замість counter += 1 використати формулу комбінаторики
# counter += k * (k - 1) * (k - 2) // 6counter += k * (k - 1) * (k - 2) // 6

n = int(input())
mas = []
counter = 0
for _ in range(n):
    x, y = map(int, input().split())
    mas.append([x, y])

dx = {} # Словник для всіх x
dy = {} # Словник для всіх y

for el in mas: #Рахуємо, скільки разів з'являється кожен х та у в наших точках
    x = el[0]
    y = el[1]
    if x in dx.keys():
        dx[x] += 1
    else:
        dx[x] = 1

    if y in dy.keys():
        dy[y] += 1
    else:
        dy[y] = 1

for key in dx.keys():
    if dx[key] >= 3:
        counter += 1
for key in dy.keys():
    if dy[key] >= 3:
        counter += 1

print(counter)




