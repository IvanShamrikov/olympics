# https://uoi.eolymp.space/problems/63
# Коробка
#
# У Козака Вуса є коробка, яка може вмістити до k кілограмів включно. Якщо у коробці будуть речі, вага яких перевищує k
# кілограмів, то вона порветься. У нього також є п'ять м'ячів вагою a1,a2,a3,a4,a5 кілограмів відповідно. Також відомо,
# що вага кожного наступного м'яча більша за попередню.
# Визначте максимальну кількість м'ячів, які можна положити у коробку так, що вона не порвалася.
#
# Вхідні дані
# Перший рядок містить одне ціле число k (1≤k≤100).
# Другий рядок містить п('ять цілих чисел a1,a2,a3,a4,a5 (1≤a≤25). Гарантується, що кожне наступне число більше за '
# попереднє.)
#
# Вихідні дані

# Приклад 1
# Вхідні дані
# 10
# 1 4 5 7 25
# Вихідні дані
# 3

# Приклад 2
# Вхідні дані
# 4
# 1 2 3 4 5
# Вихідні дані
# 2

# Приклад 3
# Вхідні дані
# 9
# 1 2 3 4 5
# Вихідні дані
# 3

k = int(input())
balls = list(map(int, input().split()))

count = 0
current_weight = 0

for weight in balls:
    if current_weight + weight <= k:
        current_weight += weight
        count += 1
    else:
        break

print(count)








