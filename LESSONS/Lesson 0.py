# https://uoi.eolymp.space/uk/problems/49
# Щасливі квитки
#
# Квиток, що складається з чотирьох цифр, вважається щасливим, якщо число, сформоване першими двома цифрами, ділиться на
# певне число k, а також число, сформоване останніми двома цифрами, ділиться на k.
# Наприклад, нехай k=3, тоді число 2199 вважається щасливим, бо 21 ділиться на 3, а також 99 ділиться на 3. А число 7565
# не є щасливим, бо число 65 на три не ділиться.
# Визначіть для трьох різних k (k=3, k=5, k=7), чи певне число n щасливе.
#
# Вхідні дані
# Перший рядок містить одне ціле число n Перший рядок містить одне ціле число n
#
# Вихідні дані
# У першому рядку виведіть «Yes», якщо n — щасливий квиток для k=3, або «No» — інакше.
# У другому рядку виведіть це саме, але для k=5.
# У третьому рядку виведіть це саме, але для k=7.
# Ви можете виводити букви у будь-якому регістрі.
#
# Приклади
#
# Вхідні дані #1
# 6075
# Відповідь #1
# Yes
# Yes
# No
#
# Вхідні дані #2
# 6342
# Відповідь #2
# Yes
# No
# Yes

n = input()
for k in [3,5,7]:
    print(int(n[:2]), int(n[2:]))
    if int(n[:2])%k==0 and int(n[2:])%k == 0:
        print("Yes")
    else:
        print("No")

